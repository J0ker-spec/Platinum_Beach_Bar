import { useStore } from "@/src/store";
import { colors, type } from "@/src/theme";
import { BackHeader, Button, FilterChip, Screen, TextField } from "@/src/ui";
import { Lock } from "lucide-react-native";
import { useLocalSearchParams, useRouter } from "expo-router";
import { useState } from "react";
import { Text, View } from "react-native";

export default function EmployeeForm() {
  const router = useRouter();
  const { id } = useLocalSearchParams<{ id?: string }>();
  const { employees, upsertEmployee, setSnack, getEmployee: findEmployee } = useStore();
  const existing = id ? findEmployee(String(id)) : undefined;
  const nextId = `EMP-${String(employees.filter((e) => !e.isAdmin).length + 8).padStart(4, "0")}`;
  const [name, setName] = useState(existing ? `${existing.firstName} ${existing.lastName}` : "");
  const [email, setEmail] = useState(existing?.email ?? "");
  const [phone, setPhone] = useState(existing?.phone ?? "");
  const [title, setTitle] = useState(existing?.title ?? "");
  const [status, setStatus] = useState<"Active" | "Inactive">(existing?.status ?? "Active");
  const [notes, setNotes] = useState("");
  const [submitted, setSubmitted] = useState(false);

  const errors = {
    name: !name.trim() ? "Full name is required" : undefined,
    email: !/^\S+@\S+\.\S+$/.test(email) ? "Enter a valid email address" : undefined,
    title: !title.trim() ? "Job title is required" : undefined,
  };

  const save = async () => {
    setSubmitted(true);
    if (errors.name || errors.email || errors.title) return;
    const [first, ...rest] = name.trim().split(/\s+/);
    const last = rest.join(" ");
    try {
      await upsertEmployee({
        id: existing?.id ?? nextId,
        firstName: first,
        lastName: last,
        email,
        phone,
        title,
        status,
        initials: `${first[0] ?? ""}${last[0] ?? ""}`.toUpperCase(),
        accent: existing?.accent ?? colors.primary,
      });
      setSnack({ message: existing ? "Employee details saved" : "Employee added", tone: "success" });
      router.back();
    } catch {
      setSnack({ message: "Couldn't save the employee. Try again.", tone: "warning" });
    }
  };

  return (
    <Screen scroll>
      <BackHeader title={existing ? "Edit employee" : "Add employee"} onBack={() => router.back()} />
      <View style={{ gap: 14 }}>
        <Text style={[type.section, { color: colors.text }]}>Personal information</Text>
        <TextField label="Full name *" value={name} onChangeText={setName} placeholder="e.g. Taylor Morgan" error={submitted ? errors.name : undefined} />
        <TextField label="Email *" value={email} onChangeText={setEmail} placeholder="name@company.example" keyboardType="email-address" error={submitted ? errors.email : undefined} />
        <TextField label="Phone number" value={phone} onChangeText={setPhone} placeholder="+1 555 000 0000" keyboardType="phone-pad" />

        <Text style={[type.section, { color: colors.text, marginTop: 8 }]}>Employment information</Text>
        <TextField label="Job title *" value={title} onChangeText={setTitle} placeholder="e.g. Barista" error={submitted ? errors.title : undefined} />
        <View style={{ gap: 6 }}>
          <Text style={[type.label, { color: colors.textSecondary }]}>Employment status</Text>
          <View style={{ flexDirection: "row", gap: 8 }}>
            {(["Active", "Inactive"] as const).map((s) => (
              <FilterChip key={s} label={s} active={status === s} onPress={() => setStatus(s)} />
            ))}
          </View>
        </View>
        <TextField
          label="Employee ID — Assigned automatically"
          value={existing?.id ?? nextId}
          editable={false}
          right={<Lock size={16} color={colors.muted} />}
          helper="Generated by the system and cannot be edited."
        />
        <TextField label="Internal notes" value={notes} onChangeText={setNotes} placeholder="Optional" />
        <Button label={existing ? "Save changes" : "Save employee"} onPress={save} />
        <Button label="Cancel" variant="secondary" onPress={() => router.back()} />
      </View>
    </Screen>
  );
}
